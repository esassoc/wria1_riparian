def assign_tier(chk, srz, ti, fish):
    """Reimplementation of preprocess_dashboard.py's assign_tier(), operating on
    the bids-table column values (chk, srz, ti, fish) instead of a DataFrame row."""
    chin = chk == "Y"
    nook = srz in NOOKSACK_ZONES
    temp = ti == 1
    fish_flag = fish == "fish"

    if chin and nook and temp:
        return "P1"
    if chin and nook and not temp:
        return "P2"
    if fish_flag and not chin and temp:
        return "P2"
    if fish_flag and nook and not chin and not temp:
        return "P3"
    if fish_flag and not nook and temp:
        return "P3"
    if fish_flag and not nook and not temp:
        return "P4"
    return "P5"


def _to_float(v):
    """Parse a CSV cell to float, treating blank/unparseable as missing (None)."""
    if v is None or v == "":
        return None
    try:
        return float(v)
    except ValueError:
        return None


def compute_waterbody_data(csv_path):
    """Stream BID_ZID_LC_20260501.csv once and return (waterbody_bids, waterbody_out):
      waterbody_bids -- set of BIDs with any PositionWaterbody == "Waterbody" row
                        (used by compute_zone_canopy_height to exclude those BIDs
                        from the scored zones rows).
      waterbody_out  -- {bid: {"rid": str, "lc": [9 proportions], "sqft": int, "wt": str}}
                        per-BID in-channel landcover, built directly from this CSV.

    Fix 2 (waterbody_bids NaN groupby): the upstream bid_explorer_data.json's
    waterbody_bids table is built in preprocess_dashboard.py (read-only, RF_Test)
    via `wb_rows.groupby(["BID", "Landcover"])`. pandas groupby drops NaN group
    keys by default. A handful of waterbody rows have a blank/NaN Landcover
    (read as NaN by pandas), and for 4 BIDs that is EVERY waterbody row they
    have -- so those BIDs vanish entirely from the grouped output and never
    reach the JSON. Confirmed against the JSON: this CSV has 1,224 distinct
    waterbody BIDs (PositionWaterbody == "Waterbody"); the JSON's
    waterbody_bids has only 1,220. The 4 missing are L667_2, L677_2, L684_1,
    L105_2 -- each has Zone == "lake" and a blank Landcover on every one of
    its waterbody rows.

    Rather than patch pandas output we cannot re-run (RF_Test is read-only),
    this recomputes waterbody_bids directly from the same CSV already streamed
    for canopy height, using a plain dict accumulation that has no NaN-key
    special case: a blank/unrecognized Landcover value simply doesn't map to
    any of the 9 LC_INDEX slots (matching upstream's treatment of any
    non-LC_ORDER landcover string) and the BID is still retained.
    """
    t0 = time.time()

    waterbody_bids = set()
    # bid -> [rid, sqft_by_lc_index (9 floats), total_sqft, {"river"/"lake" zone strings seen}]
    wb_acc = {}
    with open(csv_path, "r", encoding="utf-8-sig", newline="") as f:
        reader = csv.reader(f)
        header = next(reader)
        bid_i = header.index("BID")
        rid_i = header.index("RID")
        zone_i = header.index("Zone")
        lc_i = header.index("Landcover")
        sqft_i = header.index("SQFT")
        pw_i = header.index("PositionWaterbody")
        for row in reader:
            if row[pw_i] != "Waterbody":
                continue
            bid = row[bid_i]
            waterbody_bids.add(bid)

            sqft = _to_float(row[sqft_i]) or 0.0
            acc = wb_acc.get(bid)
            if acc is None:
                acc = [row[rid_i], [0.0] * 9, 0.0, set()]
                wb_acc[bid] = acc
            idx = LC_INDEX.get(row[lc_i])
            if idx is not None:
                acc[1][idx] += sqft
            acc[2] += sqft
            zone_val = row[zone_i]
            if zone_val in ("river", "lake"):
                acc[3].add(zone_val)

    waterbody_out = {}
    for bid, (rid, lc_sqft, total_sqft, zone_set) in wb_acc.items():
        lc_pct = [round(v / total_sqft, 2) if total_sqft > 0 else 0.0 for v in lc_sqft]
        wt = "river" if "river" in zone_set else ("lake" if "lake" in zone_set else "")
        waterbody_out[bid] = {
            "rid": rid,
            "lc": lc_pct,
            "sqft": int(round(total_sqft, 0)),
            "wt": wt,
        }

    print(f"    LC pass 1: {len(waterbody_bids):,} waterbody BIDs excluded from "
          f"the scored zones rows; {len(waterbody_out):,} waterbody_bids rows built "
          f"({time.time()-t0:.1f}s)")
    return waterbody_bids, waterbody_out


def compute_zone_canopy_height(csv_path, waterbody_bids):
    """Stream BID_ZID_LC_20260501.csv and return {(bid, z): (sum_h_sqft, sum_sqft)}
    for Forest polygons only, plus the same per (bid, z) Forest SQFT total for
    validation against the upstream zones.lc0 * sqft.

    `waterbody_bids` (from compute_waterbody_data) is the set of BIDs to exclude.
    """
    t0 = time.time()

    sums = {}  # (bid, z) -> [sum_h_sqft, sum_sqft]
    n_rows = 0
    n_forest = 0
    n_reclassed = 0
    with open(csv_path, "r", encoding="utf-8-sig", newline="") as f:
        reader = csv.reader(f)
        header = next(reader)
        bid_i = header.index("BID")
        zone_i = header.index("Zone")
        lc_i = header.index("Landcover")
        sqft_i = header.index("SQFT")
        comp_i = header.index("Composition")
        ch_i = header.index("CanopyHeight")
        fh_i = header.index("ForestHeight")

        for row in reader:
            n_rows += 1
            z = ZONE_TO_IDX.get(row[zone_i])
            if z is None:
                continue  # river/lake (or unrecognized) zone -- excluded from scored zones
            bid = row[bid_i]
            if bid in waterbody_bids:
                continue

            comp = _to_float(row[comp_i])
            fh = _to_float(row[fh_i])
            landcover = row[lc_i]
            if comp is not None and fh is not None and 0 < fh <= RECLASS_MAX_HT:
                n_reclassed += 1
                landcover = "Shrub/Woodland"  # reclassified -- NOT Forest, regardless of source class
            if landcover != "Forest":
                continue
            n_forest += 1

            sqft = _to_float(row[sqft_i]) or 0.0
            if sqft <= 0:
                continue
            ch = _to_float(row[ch_i])
            height_for_m = ch if ch is not None else fh
            if height_for_m is None:
                continue

            key = (bid, z)
            acc = sums.get(key)
            if acc is None:
                sums[key] = [height_for_m * sqft, sqft]
            else:
                acc[0] += height_for_m * sqft
                acc[1] += sqft

    print(f"    LC pass 2: {n_rows:,} rows, {n_forest:,} Forest polygons "
          f"({n_reclassed:,} reclassified away) in {time.time()-t0:.1f}s total")
    return sums

def load_or_compute_lc_derived(refresh=False):
    """Return (waterbody_bids, waterbody_out, canopy_sums) from LC_CACHE, computing
    them from LC_CSV (and writing the cache) when the cache is missing or refresh=True.
    Shapes are identical to compute_waterbody_data()/compute_zone_canopy_height()."""
    if not refresh and os.path.isfile(LC_CACHE):
        with open(LC_CACHE, "r", encoding="utf-8") as f:
            c = json.load(f)
        waterbody_bids = set(c["waterbody_bids"])
        waterbody_out = c["waterbody_out"]
        canopy_sums = {}
        for k, v in c["canopy_sums"].items():
            bid, z = k.rsplit("|", 1)
            canopy_sums[(bid, int(z))] = v
        print(f"    LC derived data loaded from cache {os.path.relpath(LC_CACHE, SCRIPT_DIR)} "
              f"(source {c.get('source')}, {len(waterbody_out):,} waterbody rows, "
              f"{len(canopy_sums):,} canopy keys)")
        return waterbody_bids, waterbody_out, canopy_sums

    if not os.path.isfile(LC_CSV):
        raise RuntimeError(
            f"Landcover CSV not found at {LC_CSV} and no cache at {LC_CACHE} "
            "(or --refresh-lc-cache was requested). Restore the CSV or the cache."
        )
    waterbody_bids, waterbody_out = compute_waterbody_data(LC_CSV)
    canopy_sums = compute_zone_canopy_height(LC_CSV, waterbody_bids)
    os.makedirs(os.path.dirname(LC_CACHE), exist_ok=True)
    payload = {
        "source": os.path.basename(LC_CSV),
        "source_bytes": os.path.getsize(LC_CSV),
        "waterbody_bids": sorted(waterbody_bids),
        "waterbody_out": waterbody_out,
        "canopy_sums": {f"{bid}|{z}": v for (bid, z), v in canopy_sums.items()},
    }
    with open(LC_CACHE, "w", encoding="utf-8") as f:
        json.dump(payload, f, separators=(",", ":"))
    print(f"    LC derived data written to cache {os.path.relpath(LC_CACHE, SCRIPT_DIR)} "
          f"({os.path.getsize(LC_CACHE)/1e6:.1f} MB)")
    return waterbody_bids, waterbody_out, canopy_sums

